'use client';


import { Combobox as ComboboxPrimitive } from '@base-ui/react';
import { CheckIcon, ChevronDownIcon, XIcon } from 'lucide-react';
import * as React from 'react';
import { cn } from '@/lib/utils';
import { Button } from '@/components/ui/button';
import {
  InputGroup,
  InputGroupAddon,
  InputGroupButton,
  InputGroupInput,
} from '@/components/ui/input-group';

const Combobox = ComboboxPrimitive.Root;

function ComboboxValue({ ...props }: ComboboxPrimitive.Value.Props) {
  return <ComboboxPrimitive.Value data-slot="combobox-value" {...props} />;
}

const ComboboxTrigger = React.forwardRef<HTMLButtonElement, ComboboxPrimitive.Trigger.Props>(
  function ComboboxTrigger({ className, children, ...props }, ref) {
    return (
      <ComboboxPrimitive.Trigger
        ref={ref}
        data-slot="combobox-trigger"
        className={cn("[&_svg:not([class*='size-'])]:size-4", className)}
        {...props}
      >
        {children}
        <ChevronDownIcon className="pointer-events-none size-4 text-foreground" />
      </ComboboxPrimitive.Trigger>
    );
  },
);

function ComboboxClear({ className, ...props }: ComboboxPrimitive.Clear.Props) {
  return (
    <ComboboxPrimitive.Clear
      data-slot="combobox-clear"
      render={<InputGroupButton variant="ghost" size="icon-xs" />}
      className={cn(className)}
      {...props}
    >
      <XIcon className="pointer-events-none" />
    </ComboboxPrimitive.Clear>
  );
}

function ComboboxInput({
  className,
  children,
  disabled = false,
  showTrigger = true,
  showClear = false,
  label,
  required = false,
  readOnly,
  hasValue = false,
  ...props
}: ComboboxPrimitive.Input.Props & {
  showTrigger?: boolean;
  showClear?: boolean;
  label?: string;
  required?: boolean;
  readOnly?: boolean;
  hasValue?: boolean;
}) {
  const [focused, setFocused] = React.useState(false);

  const shouldFloat = focused || hasValue;

  return (
    <div
      onFocusCapture={() => setFocused(true)}
      onBlurCapture={() => setFocused(false)}
      className={cn(
        'relative',
        typeof className === 'string' && !className.includes('w-') && 'w-full',
      )}
    >
      {!disabled && label && (
        <span
          className={cn(
            'bg-background dark:bg-background/60 pointer-events-none absolute z-10 px-1 text-sm transition-all ml-3',
            'top-1/2 -translate-y-1/2',
            'text-muted-foreground',
            shouldFloat && 'text-helper -top-2 left-0 translate-y-0 text-xs',
            disabled && 'text-muted-foreground',
            readOnly && 'text-muted-foreground',
          )}
        >
          {label}
          {required && <span className="text-destructive"> *</span>}
        </span>
      )}
      <InputGroup
        className={cn(
          'w-full h-10 rounded-md border-muted-foreground',
          label && 'pt-2 pb-1.5',
          className,
        )}
      >
        <ComboboxPrimitive.Input
          render={
            <InputGroupInput
              disabled={disabled}
              placeholder={label ? undefined : props.placeholder}
            />
          }
          {...props}
        />
        <InputGroupAddon align="inline-end">
          {showTrigger && (
            <InputGroupButton
              size="xs"
              variant="ghost"
              render={<ComboboxTrigger />}
              data-slot="input-group-button"
              className="group-has-data-[slot=combobox-clear]/input-group:hidden data-pressed:bg-transparent"
              disabled={disabled}
            />
          )}
          {showClear && <ComboboxClear disabled={disabled} />}
        </InputGroupAddon>
      </InputGroup>
      {children}
    </div>
  );
}

