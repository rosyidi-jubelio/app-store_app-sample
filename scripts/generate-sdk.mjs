import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const specPath = path.join(root, 'openapi/jubelio-open-api.yaml');
const outPath = path.join(root, 'src/lib/jubelio/schema.ts');

const MERCHANT_HEADER_REF = '#/components/parameters/JblMerchantId';

const spec = parse(await readFile(specPath, 'utf8'));

for (const pathItem of Object.values(spec.paths)) {
  const holders = [pathItem, ...Object.values(pathItem).filter((v) => v && typeof v === 'object' && !Array.isArray(v))];
  for (const holder of holders) {
    if (Array.isArray(holder.parameters)) {
      holder.parameters = holder.parameters.filter((p) => p.$ref !== MERCHANT_HEADER_REF);
    }
  }
}

const ast = await openapiTS(spec, { rootTypes: true, rootTypesNoSchemaPrefix: true });
const banner = '/* Generated by scripts/generate-sdk.mjs from openapi/jubelio-open-api.yaml. Do not edit. */\n\n';
await writeFile(outPath, banner + astToString(ast));
console.log(`wrote ${path.relative(root, outPath)}`);
